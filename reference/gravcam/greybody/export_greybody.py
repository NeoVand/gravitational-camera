"""Export the greybody table of chapter 11.3 (table.npz, made by greybody.py and table.py in this folder) into
app/src/lib/tutorial/live/hole-against-sky-data.ts, for the interactive figure HoleAgainstSky.svelte.

The table holds Gamma_l(x) for l = 2..40 on 400 values of x = GM omega / c^3: 0.01 to 2.00 in hundredths, then 2.02 to
6.00 in fiftieths. Each degree is kept where 1e-7 < Gamma < 1 - 1e-7 (from its first such x to its last); below that
stretch it is read as 0 and above it as 1. Degrees 2, 3 and 4 are kept from the first x, so that the long-wave end
(Page's x^6) can be checked. Degrees whose Gamma stays below 1e-7 for every x <= 6 (34 to 40) are left out. Six
significant figures.

Run from this folder: python table.py, then python export_greybody.py table.npz ../../../app/src/lib/tutorial/live/hole-against-sky-data.ts
then prettier --write on the output.
"""
import sys

import numpy as np

EPS = 1e-7
KEEP_ALL = (2, 3, 4)


def g6(v: float) -> str:
    s = '%.6g' % v
    return s


def main(src: str, out: str) -> None:
    d = np.load(src)
    xs, ls, G = d['x'], d['l'], d['G']
    assert G.shape == (len(xs), len(ls))
    rows = []
    dropped = []
    for j, l in enumerate(ls):
        g = np.clip(G[:, j], 0.0, 1.0)
        inside = np.where((g > EPS) & (g < 1 - EPS))[0]
        if int(l) in KEEP_ALL:
            i0 = 0
            i1 = int(inside[-1])
        elif len(inside) == 0:
            assert g.max() < EPS, (l, g.max())
            dropped.append(int(l))
            continue
        else:
            i0, i1 = int(inside[0]), int(inside[-1])
        # the values outside the stretch are read as 0 below and 1 above: check that this is so to EPS
        assert np.all(g[:i0] <= EPS), l
        assert np.all(g[i1 + 1:] >= 1 - EPS), l
        rows.append((int(l), i0, [g6(v) for v in g[i0:i1 + 1]]))

    xs_text = ', '.join('%.2f' % v for v in xs)
    assert np.allclose([float(t) for t in xs_text.split(', ')], xs, atol=1e-12)
    lines = []
    lines.append('/**')
    lines.append(' * The spin-two greybody factors Γ_ℓ(x) of a Schwarzschild hole, for chapter 11.3\'s interactive')
    lines.append(' * HoleAgainstSky (HoleAgainstSky.svelte), with x = GMω/c³. Each is the share of an incoming wave of degree ℓ')
    lines.append(' * that a hole absorbs, from a numerical solution of the Regge–Wheeler equation, purely ingoing at the')
    lines.append(' * horizon and split into ingoing and outgoing waves far away (reference/gravcam/greybody/greybody.py and table.py,')
    lines.append(' * flux conserved to 10⁻⁶).')
    lines.append(' *')
    lines.append(' * `X` holds the 400 values of x: 0.01 to 2.00 in hundredths, then 2.02 to 6.00 in fiftieths. Each entry of')
    lines.append(' * `GREYBODY` keeps one degree ℓ where 10⁻⁷ < Γ_ℓ < 1 − 10⁻⁷: Γ_ℓ(X[i]) is `values[i − from]` on that')
    lines.append(' * stretch, 0 below it and 1 above it. Degrees 2, 3 and 4 are kept from the first x. Degrees ' +
                 f'{dropped[0]} to {dropped[-1]}' if dropped else '')
    lines.append(' * stay below 10⁻⁷ for every x ≤ 6 and are left out. Six significant figures.')
    lines.append(' *')
    lines.append(' * Generated by reference/gravcam/greybody/export_greybody.py, from the table that table.py there writes;')
    lines.append(' * do not edit by hand.')
    lines.append(' */')
    lines.append('')
    lines.append('/** The 400 values of x = GMω/c³ of the table. */')
    lines.append(f'export const X: readonly number[] = [{xs_text}];')
    lines.append('')
    lines.append('/** One degree ℓ of the table: Γ_ℓ(X[i]) = values[i − from] on its stretch, 0 below and 1 above. */')
    lines.append('export type GreybodyRow = { readonly l: number; readonly from: number; readonly values: readonly number[] };')
    lines.append('')
    lines.append(f'/** The degrees ℓ = {rows[0][0]} to {rows[-1][0]}. */')
    lines.append('export const GREYBODY: readonly GreybodyRow[] = [')
    for l, i0, vals in rows:
        lines.append(f'\t{{ l: {l}, from: {i0}, values: [{", ".join(vals)}] }},')
    lines.append('];')
    lines.append('')
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    n = sum(len(r[2]) for r in rows)
    print(f'{len(rows)} degrees ({rows[0][0]}..{rows[-1][0]}), {n} values, dropped {dropped}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
